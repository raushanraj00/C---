#include <iostream>
using namespace std;
int main(){
    //BITWISE OPERATORS
    int a = 2&3; 
    cout << a << "\n"; // AND operator
    int b = 2|3; 
    cout << b << "\n"; // OR operator
    int c = 2^3; 
    cout << c << "\n"; // XOR operator
    int d = ~2; 
    cout << d << "\n"; // NOT operator
    int e = 2<<1;
    cout << e << "\n"; // LEFT SHIFT operator
    int f = 2>>1;
    cout << f << "\n"; // RIGHT SHIFT operator
    
    //Assignment operator
     
}